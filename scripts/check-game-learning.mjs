import assert from 'node:assert/strict';
import { assessDictation, spelling, scheduleMistake, schedulePractice, answerReview, reviewCards, dueCards, reviewStage, reviewExercise, gameSummary, reviewCorrect } from '../public/game-learning.js';
assert.equal(assessDictation('I see their house.', 'I see there house').correct, false);
assert.equal(assessDictation("I can't swim.", 'I cant swim').correct, false);
assert.equal(assessDictation('It is their house.', 'it is their house!').correct, true);
let a = assessDictation('I see their house.', 'I their house');
assert.equal(a.matched, 3);
assert.equal(a.tokens.filter(t => !t.correct).length, 1);
a = assessDictation('I like tea.', 'I really like tea');
assert.equal(a.correct, false);
assert.equal(a.matched, 3);
assert.equal(a.tokens.filter(t => t.extra).length, 1);
assert.notEqual(spelling("parents'"), spelling("parent's"));
const card = { key: 'escribe|cat', game: 'escribe', prompt: 'gato', accepted: ['cat'], explanation: 'cat — gato' };
let queue = scheduleMistake({}, card, '2026-09-13');
assert.equal(queue[card.key].due, '2026-09-14');
assert.equal(dueCards(queue, '2026-09-13').length, 0);
assert.equal(answerReview(queue, card.key, true, '2026-09-13')[card.key].stage, 0, 'Immediate rehearsal does not advance delayed checks');
let passed = answerReview(queue, card.key, true, '2026-09-14');
assert.equal(passed[card.key].stage, 1);
assert.equal(passed[card.key].due, '2026-09-17');
passed = answerReview(passed, card.key, true, '2026-09-14');
assert.equal(passed[card.key].stage, 1, 'No second advance on the same day');
passed = answerReview(passed, card.key, true, '2026-09-17');
assert.equal(passed[card.key].stage, 2);
assert.equal(passed[card.key].due, '2026-09-24');
passed = answerReview(passed, card.key, true, '2026-09-24');
assert.equal(passed[card.key].stage, 3);
assert.equal(passed[card.key].due, '2026-10-24');
passed = answerReview(passed, card.key, true, '2026-10-24', true);
assert.equal(passed[card.key].stage, 0, 'Help resets the retention checks');
assert.equal(passed[card.key].due, '2026-10-25');
assert.equal(schedulePractice(passed, card, '2026-10-24')[card.key].due, '2026-10-25', 'Replaying missions cannot postpone a scheduled review');
assert.equal(schedulePractice({}, card, '2026-09-13')[card.key].misses, 0, 'Schedule successful items too, without calling them mistakes');
assert.equal(reviewStage({ stage: NaN }), 0);
assert.equal(reviewExercise({ ...card, variants: [null].filter(Boolean) }).prompt, card.prompt);
const failed = answerReview(queue, card.key, false, '2026-09-14');
assert.equal(failed[card.key].due, '2026-09-15');
assert.equal(queue[card.key].due, '2026-09-14', 'Do not mutate the previous queue');
assert.equal(reviewCards({ broken: null, other: {}, [card.key]: queue[card.key] }).length, 1);
assert.equal(reviewCorrect(card, ' CAT! '), true);
assert.equal(reviewCorrect(card, ''), false);
assert.deepEqual(gameSummary({ aciertos: 6, conPista: 2, fallos: 3, nose: 1 }), { correct: 6, assisted: 2, independent: 4, wrong: 3, unknown: 1, total: 10, accuracy: 40 });
assert.equal(gameSummary({ resueltas: 6, fallos: 2, conPista: 2 }).independent, 4);
assert.equal(gameSummary({}).accuracy, null);
console.log('PASS: spelling, homophones, alignment, extras, assistance, persisted errors, delayed retrieval, malformed data');
