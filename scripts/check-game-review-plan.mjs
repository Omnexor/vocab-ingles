import assert from 'node:assert/strict';
import { reviewPlan, reviewSessionValid, scheduleMistake, answerReview, reviewCards } from '../public/game-learning.js';
const day='2026-09-15';
const card={key:'a',game:'escribe',prompt:'gato',accepted:['cat'],explanation:'cat — gato',due:day};
const queue={a:card,b:{...card,key:'b',mission:'travel-words',due:'2026-09-16'},c:{...card,key:'c',stage:3,due:'2026-10-15'},broken:{...card,key:'x',due:'2026-99-99'}};
let plan=reviewPlan(queue,day);
assert.equal(plan.total,3); assert.equal(plan.due,1); assert.equal(plan.upcoming,2); assert.equal(plan.next,'2026-09-16');
assert.equal(plan.groups[0].game,'escribe'); assert.equal(plan.groups[0].maintenance,1);
assert.equal(reviewCards({x:{...card,due:'2026-02-30'}}).length,0);
let answered=answerReview(queue,'a',true,day);
for(let i=0;i<25;i++) answered=answerReview(answered,'a',true,day);
plan=reviewPlan(answered,day);
assert.equal(plan.today.independent,1); assert.equal(plan.today.early,0,'Replays cannot evict the first daily result');
assert.equal(answered.a.history.length,12);
answered=scheduleMistake(answered,card,day);
assert.equal(reviewPlan(answered,day).groups.find(g=>g.game==='escribe').support,1);
assert.equal(reviewPlan(answered,day).today.independent,1);
const assisted=answerReview(queue,'a',true,day,true);
assert.equal(reviewPlan(assisted,day).today.assisted,1);
const failed=answerReview(queue,'a',false,day);
assert.equal(reviewPlan(failed,day).today.wrong,1);
const early=answerReview(queue,'b',true,day);
assert.equal(reviewPlan(early,day).today.early,1);
const run={date:day,gameId:null,items:[card],i:0,response:null};
assert.ok(reviewSessionValid(run,[card],day));
assert.equal(reviewSessionValid({...run,items:[null]},[card],day),false);
assert.equal(reviewSessionValid({...run,missionId:'travel-words'},[card],day),false);
assert.equal(reviewSessionValid(run,[card],'2026-09-16'),false);
assert.equal(reviewSessionValid({...run,i:1},[card],day),false);
assert.equal(reviewPlan({},day).next,null);
console.log('PASS: due/future groups, valid dates, maintenance, support, first-attempt counts after 25 replays, legacy and malformed sessions');
