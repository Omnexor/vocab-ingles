import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE
  ? pathToFileURL(resolve(process.env.PLAYWRIGHT_MODULE)).href : 'playwright');
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3000');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(async () => {
    const names = await caches.keys();
    const name = names.find(n => n === 'vocab-v52');
    if (!name) return false;
    const cache = await caches.open(name);
    const assets = ['index.html', 'app.js', 'learning-engine.js', 'grammar-practice.js', 'game-learning.js', 'game-missions.js', 'game-audio.js', 'lessons.js', 'vocabulario.json'];
    return (await Promise.all(assets.map(path => cache.match(`./${path}`)))).every(Boolean);
  });
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('button', { name: 'Aprender', exact: true }).click();
  await page.locator('#learning-next button').click();
  await page.locator('#start-production').click();
  await page.locator('#written-response').fill('offline draft');
  await page.reload();
  await page.getByRole('button', { name: 'Aprender', exact: true }).click();
  await page.locator('#learning-next button').click();
  await page.locator('#resume-quiz').click();
  assert.equal(await page.locator('#written-response').inputValue(), 'offline draft');
  await page.locator('#nose').click();
  assert.ok(await page.locator('.explain').isVisible());
  await page.locator('#back-lecciones').click();
  await page.getByRole('button', { name: 'Juegos', exact: true }).click();
  await page.locator('#juegos-lista [data-juego="rapida"]').click();
  await page.locator('#nose').click();
  await page.locator('#back-juegos').click();
  await page.locator('#open-game-review').click();
  assert.ok(await page.locator('#game-review-answer').isVisible());
  const pending = await page.evaluate(() => Object.values(JSON.parse(localStorage.getItem('vocab-ingles:v1')).gameReview));
  assert.ok(pending.length);
  await page.locator('#back-juegos').click();
  await page.locator('#mission-start').click();
  await page.locator('#mission-answer').fill('offline mission draft');
  await page.reload();
  await page.getByRole('button', { name: 'Juegos', exact: true }).click();
  await page.locator('#mission-start').click();
  assert.equal(await page.locator('#mission-answer').inputValue(), 'offline mission draft');
  await page.locator('#mission-skip').click();
  assert.ok(await page.locator('#mission-next').isVisible());
  await page.locator('#back-juegos').click();
  await page.locator('#mission-hub summary').click();
  await page.locator('[data-mission="listen-cafe"]').click();
  await page.locator('#task-transcript').click();
  assert.ok(await page.locator('.mission-audio .pista-box').isVisible());
  await page.locator('#mission-answer').fill('15');
  await page.locator('#mission-answer').press('Enter');
  const listening = await page.evaluate(() => JSON.parse(localStorage.getItem('vocab-ingles:v1')).missionSessions['listen-cafe']);
  assert.equal(listening.answers[0].assisted,true);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: 'SW v52, offline boot, grammar draft, game errors, written review, mission resume and audio transcript fallback offline' }));
  await context.close();
} finally { await browser.close(); }
